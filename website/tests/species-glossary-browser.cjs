const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TEST_ORIGIN || 'http://127.0.0.1:8765';
const out = process.env.TEST_OUTPUT || path.resolve(__dirname, '../test-results/species-glossary');
(async () => {
  fs.mkdirSync(out, {recursive:true});
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  try {
    await page.goto(base + '/glossary/', {waitUntil:'networkidle'});
    const reject = page.getByRole('button', {name:'Reject non-essential'});
    if (await reject.isVisible()) await reject.click();
    await page.locator('#glossary-search').fill('albie blitz');
    assert.equal(await page.locator('[data-glossary-term]:visible').count(), 1);
    assert.match(await page.locator('[data-glossary-term]:visible a').first().getAttribute('href'), /montauk-fall-run/);
    await page.locator('#glossary-search').fill('yelloweye');
    await page.locator('#glossary-region').selectOption('Alaska');
    assert.ok(await page.locator('[data-glossary-term]:visible').count() >= 2);
    await page.locator('#glossary-search').fill('boilie');
    await page.locator('#glossary-region').selectOption('United Kingdom');
    assert.equal(await page.locator('[data-glossary-term]:visible').count(), 1);
    await page.locator('#glossary-region').selectOption('Australia');
    assert.equal(await page.locator('[data-glossary-term]:visible').count(), 0);
    assert.equal(await page.locator('#glossary-empty').isVisible(), true);
    await page.locator('#glossary-search').fill('');
    await page.locator('#glossary-region').selectOption('');
    await page.locator('.field-alphabet a[href="#letter-Y"]').click();
    assert.equal(new URL(page.url()).hash, '#letter-Y');
    await page.goto(base + '/species/', {waitUntil:'networkidle'});
    assert.equal(await page.locator('[data-species-card]:visible').count(), 60);
    await page.locator('#species-more').click();
    assert.equal(await page.locator('[data-species-card]:visible').count(), 120);
    await page.locator('#species-search').fill('black rockfish');
    assert.equal(await page.locator('.field-fish-card a[href="/species/black-rockfish/"]').isVisible(), true);
    await page.goto(base + '/species/black-rockfish/', {waitUntil:'networkidle'});
    assert.ok(await page.locator('#where-to-fish .field-trip-links li').count() >= 3);
    await page.screenshot({path:path.join(out,'species-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.screenshot({path:path.join(out,'species-mobile.png')});
    await page.goto(base + '/glossary/?q=barn-doors&region=Alaska', {waitUntil:'networkidle'});
    assert.equal(await page.locator('[data-glossary-term]:visible').count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    await page.screenshot({path:path.join(out,'glossary-mobile.png')});
    assert.deepEqual(errors, []);
    const report = {passed:true,checks:16,widths:[1440,390],pageErrors:errors};
    fs.writeFileSync(path.join(out,'browser-results.json'),JSON.stringify(report,null,2));
    console.log(JSON.stringify(report));
  } finally { await browser.close(); }
})().catch(error => { console.error(error.message); process.exitCode = 1; });
